'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {chromium}=require('playwright-core');
const base=process.env.TEST_URL||'http://127.0.0.1:8877/';
const sourceSHA='724f52ffa773ef9d7fdacd3960802b5eed2fa702';
const html=fs.readFileSync('menu/start.html','utf8');
const app=fs.readFileSync('menu/app.js','utf8');
const publicCatalog=JSON.parse(fs.readFileSync('menu/products.json','utf8'));
assert(!('source_notes' in publicCatalog),'1C source notes not published');
assert(publicCatalog.products.every(p=>p.availability==='unknown'&&!('internal_code' in p)&&!('stock_quantity' in p)&&!('sku_code' in p)),'no internal identity or warehouse counts in public JSON');
const potato=publicCatalog.products.find(p=>p.id==='potato');
assert(potato&&potato.price===49.96&&potato.price_as_of==='2026-10-20','dated club reference from reviewed 1C report');
assert.equal(publicCatalog.last_reference_import.as_of,'2026-10-20T19:06:43+03:00');
assert(publicCatalog.last_reference_import.online_stock_confirmed===false,'no warehouse stock published');

const release=fs.readFileSync('menu/RELEASE.txt','utf8');
assert(release.includes(sourceSHA));
assert.equal((html.match(/class="lp-referral"/g)||[]).length,1,'one Local Point block');
assert(html.includes('store-return-link')&&html.includes('href="../"'));
assert(html.includes('href="tel:+79637940001"'));
assert(html.includes('https://wa.me/79637940001?text='));
assert(html.includes('https://berbena.pro/prorecepty?'));
assert(html.includes('local-point-logo.webp'));
assert(html.includes('https://t.me/Local_01'));
assert(html.includes('https://max.ru/u/f9LHodD0cOLOdqweo6ZD2M-8go71XGKMQN7-aZq8vsAcHJBEE3f3_rRGGqI'));
assert(!html.includes('—'),'no em dashes in static menu HTML');
assert(html.includes('app.js?v=copy-'+sourceSHA.slice(0,12)));
assert(app.includes('weightedNeeds')===false || app.includes('meal-attendance-details'),'staged app must contain attendance controls');
assert(app.includes('Выберите количество людей, время и ограничения.'),'grammatical plural after release');
assert(!app.includes('id="berbena-recipes-referral"'),'no duplicate PROРЕЦЕПТЫ block in menu code');
assert.equal((html.match(/class="cross-brand"/g)||[]).length,1,'one compact berbena referral');
assert(!app.includes('Выберите количество человек, время и ограничения.'),'outdated wording absent');
assert(app.includes('data-wish='),'per-item choice visible');
assert(app.includes('id="budget-progress"'),'budget is linked to pending basket');
assert(app.includes('Пожелание заменяет товар в заявке'),'wish price cannot be inferred from original pack');
assert(app.includes("WHATSAPP_NUMBER='79882040001'"));
assert(!app.includes("WHATSAPP_NUMBER='79882040000'"));
const worker=fs.readFileSync('menu/sw.js','utf8');
assert(worker.includes('palleta-offline-release-'+sourceSHA.slice(0,12)));
assert(worker.includes('assets/local-point-logo.webp'));
const lp=fs.readFileSync('menu/assets/local-point-logo.webp');
assert.equal(lp.toString('ascii',0,4),'RIFF');
assert.equal(lp.toString('ascii',8,12),'WEBP');
(async()=>{ const browser=await chromium.launch({executablePath:process.env.CHROME_BIN||'/usr/bin/google-chrome',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
try{
 for(const width of [360,390]){
  const context=await browser.newContext({viewport:{width,height:844}});
  const page=await context.newPage();
  const errors=[];page.on('pageerror',x=>errors.push(x.message));
  const url=new URL('menu/start.html',base).href;
  let response=await page.goto(url,{waitUntil:'networkidle',timeout:30000});
  assert(response?.ok());
  await page.getByRole('heading',{name:'Что приготовить на этой неделе?'}).waitFor();
  assert.equal(await page.locator('.lp-referral').count(),1,'no duplicate LP CTA');
  const logo=page.locator('.lp-referral-logo');
  assert(await logo.evaluate(x=>x.complete&&x.naturalWidth>0),'real LP image loads');
  assert.equal(await page.locator('.lp-referral-phone').getAttribute('href'),'tel:+79637940001');
  assert.equal(await page.locator('.lp-contact-icons a').count(),4,'four LP contacts');
  assert.equal(await page.locator('.lp-icon-tg').getAttribute('href'),'https://t.me/Local_01');
  assert.equal(await page.locator('.lp-icon-max').getAttribute('href'),'https://max.ru/u/f9LHodD0cOLOdqweo6ZD2M-8go71XGKMQN7-aZq8vsAcHJBEE3f3_rRGGqI');
  assert.equal(await page.locator('.lp-icon-call').getAttribute('href'),'tel:+79637940001');
  assert.equal(await page.locator('.lp-referral-phone').evaluate(el=>getComputedStyle(el).textDecorationLine),'none','LP phone not underlined');
  for(const node of await page.locator('.lp-contact-icons a').all()) assert((await node.boundingBox()).height>=44,'contact target 44px minimum');

  assert((await page.locator('.lp-referral-link').getAttribute('href')).startsWith('https://wa.me/79637940001?text='));
  assert.equal(await page.locator('.store-return-link').getAttribute('href'),'../');
  await page.getByRole('button',{name:'Посмотреть пример меню'}).click();
  await page.getByRole('heading',{name:'Семейное меню на 3 дня'}).waitFor();
  assert.equal(await page.locator('.slot').count(),9);
  assert.equal(await page.getByText('Какие SKU стоит проверить').count(),0,'buyer UI has no internal SKU diagnostics');
  assert.equal(await page.locator('#berbena-recipes-referral').count(),0,'duplicate promo is removed');
  assert.equal(await page.locator('a.cross-brand').count(),1,'single footer cross-brand card visible');
  const bought=page.locator('input.shopping-check').first();
  const whatsapp=page.locator('#whatsapp');
  const beforeBought=await whatsapp.getAttribute('href');
  assert(beforeBought?.startsWith('https://wa.me/79882040001?text='));
  await bought.check();
  const afterBought=await whatsapp.getAttribute('href');
  assert.notEqual(afterBought,beforeBought,'purchased product removed from outgoing order');
  assert(new URL(afterBought).searchParams.get('text').length<new URL(beforeBought).searchParams.get('text').length);
  const boughtName=(await bought.getAttribute('aria-label')).replace(/^Куплено: /,'');
  assert(!new URL(afterBought).searchParams.get('text').includes('• '+boughtName+' —'),'actual SKU absent from WhatsApp order');
  await page.reload({waitUntil:'networkidle'});
  await page.getByRole('button',{name:'Продолжить сохранённое меню'}).click();
  assert(await bought.isChecked(),'purchased item stays purchased after reload');
  assert.equal(await whatsapp.getAttribute('href'),afterBought,'saved WhatsApp message stays correctly filtered');
  await bought.uncheck();
  assert.equal(await whatsapp.getAttribute('href'),beforeBought,'unchecking restores outgoing order');
  for(const cb of await page.locator('input.shopping-check').all())await cb.check();
  assert.equal(await whatsapp.getAttribute('href'),null,'zero pending items must not create empty order');
  assert.equal(await whatsapp.getAttribute('aria-disabled'),'true');
  for(const cb of await page.locator('input.shopping-check').all())await cb.uncheck();
  assert.equal(await whatsapp.getAttribute('href'),beforeBought,'restored cart is available for test purchase');
  const wishInput=page.locator('input[data-wish]').first();
  const originalWishHref=await whatsapp.getAttribute('href');
  await wishInput.fill('Черри');
  const prefHref=await whatsapp.getAttribute('href');
  assert(prefHref&&prefHref!==originalWishHref,'typing a brand/sort immediately updates WhatsApp');
  assert(new URL(prefHref).searchParams.get('text').includes('хочу «Черри»'),'requested alternate captured in real payload');
  await page.reload({waitUntil:'networkidle'});
  await page.getByRole('button',{name:'Продолжить сохранённое меню'}).click();
  assert.equal(await wishInput.inputValue(),'Черри','product wishlist persists after reload');
  assert.equal(await whatsapp.getAttribute('href'),prefHref,'outgoing message remains consistent across reload');
  await wishInput.fill('');
  assert.equal(await whatsapp.getAttribute('href'),originalWishHref,'clearing wish restores requested catalog product');
  const storeAlt=page.locator('.panel').filter({has:page.locator('#check-count')}).locator('select[data-ingredient]').first();
  assert(await storeAlt.count()>0,'store basket offers a pack/product alternative');
  const originalId=await storeAlt.inputValue();
  const variant=await storeAlt.locator('option').evaluateAll((options,id)=>options.filter(o=>o.value!==id).map(o=>({id:o.value,name:o.textContent.split(' · ')[0]}))[0],originalId);
  assert(variant?.id,'alternate product has a valid id');
  await storeAlt.selectOption(variant.id);
  const alternateHref=await whatsapp.getAttribute('href');
  assert(alternateHref&&alternateHref!==beforeBought,'changing pack changes WhatsApp request');
  assert(new URL(alternateHref).searchParams.get('text').includes('• '+variant.name+' —'),'chosen alternative appears in real WhatsApp text');
  await storeAlt.selectOption(originalId);
  assert.equal(await whatsapp.getAttribute('href'),beforeBought,'switching back restores original request');

  assert.equal(await page.locator('details.meal-attendance-details[open]').count(),0);
  await page.locator('[data-attendance-key="0-lunch"] > summary').click();
  await page.locator('[data-attendance="0-lunch"]').selectOption('2');
  assert((await page.locator('#app').innerText()).includes('2 порций'),'meal portion recalculated');
  await page.getByRole('button',{name:'Все едят дома'}).click();
  assert((await page.locator('#app').innerText()).includes('9 из 9 домашних блюд'));
  await page.getByRole('button',{name:'← На главную'}).click();
  await page.getByRole('button',{name:'Составить меню'}).click();
  for(const x of ['7','4','60','12000'])await page.locator('[data-answer="'+x+'"]').click();
  await page.locator('#next').click();
  assert.equal(await page.locator('.slot').count(),21);
  assert((await page.locator('#budget-progress').innerText()).includes('12'),'family budget shown after 7-day choice');
  assert(new URL(await page.locator('#whatsapp').getAttribute('href')).searchParams.get('text').includes('Ориентир бюджета на товары Паллеты'),'budget included in outgoing staff request');
  await page.getByRole('button',{name:'В выходные обед-пикник'}).click();
  assert((await page.locator('#app').innerText()).includes('19 из 19 домашних блюд'));
  await page.getByRole('button',{name:'Пропустить обеды в будни'}).click();
  assert((await page.locator('#app').innerText()).includes('14 из 14 домашних блюд'));
  const wa=await page.locator('#whatsapp').getAttribute('href');
  assert(wa.startsWith('https://wa.me/79882040001?text='));
  const message=new URL(wa).searchParams.get('text');
  assert(message.includes('Список покупок:'));
  assert(!message.includes('Куриные потроха'),'external meat must not be in Palleta order');
  const info=await page.evaluate(()=>({width:innerWidth,doc:document.documentElement.scrollWidth}));
  assert(info.doc<=width+1,'mobile horizontal overflow '+JSON.stringify(info));
  assert(await page.locator('.lp-referral-link').isVisible());
  assert.deepEqual(errors,[]);
  console.log('PASS unified /menu/ at '+width+'px: attendance, picnic, brand, WhatsApp, no overflow');
  await context.close();
 }
}finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
